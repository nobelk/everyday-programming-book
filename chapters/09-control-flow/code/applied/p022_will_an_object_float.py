"""Problem 22 — Will an object float?

Domain: Physics. Chapter 9 (Control Flow), conditionals.

Problem
-------
An object floats in water if its density is less than 1.0 g/cm³.

Expected output
---------------
Object floats
"""


density = 0.8
if density < 1.0:
    print("Object floats")
else:
    print("Object sinks")
